#!/usr/bin/env node
/**
 * Writes public/assets/imgs/template/logo/favicon.svg using the brand colours
 * defined in src/styles/elora/utils/_colors.scss.
 *
 * The favicon is a standalone file the browser loads on its own, so it cannot
 * read the site's CSS variables - it is the one place a brand colour has to be
 * written out literally. Generating it from the same source keeps it in sync
 * instead of leaving a stale hex behind after a palette change.
 *
 * Run after editing the $brand-* variables:
 *     node scripts/generate-favicon.mjs
 */
import fs from 'node:fs';
import path from 'node:path';
import { fileURLToPath } from 'node:url';

const __dirname = path.dirname(fileURLToPath(import.meta.url));
const COLORS = path.join(__dirname, '..', 'src', 'styles', 'elora', 'utils', '_colors.scss');
const OUT = path.join(__dirname, '..', 'public', 'assets', 'imgs', 'template', 'logo', 'favicon.svg');

const scss = fs.readFileSync(COLORS, 'utf-8');
function brand(name) {
  const m = scss.match(new RegExp(`\\$${name}\\s*:\\s*(#[0-9a-fA-F]{3,8})\\s*;`));
  if (!m) {
    console.error(`Could not find $${name} in ${path.relative(process.cwd(), COLORS)}`);
    process.exit(1);
  }
  return m[1];
}

const from = brand('brand-1');
const to = brand('brand-2');

const svg = `<!-- Generated by scripts/generate-favicon.mjs from the $brand-* values
     in src/styles/elora/utils/_colors.scss. Do not edit by hand. -->
<svg width="64" height="64" viewBox="0 0 64 64" fill="none" xmlns="http://www.w3.org/2000/svg">
  <defs>
    <linearGradient id="brandMark" x1="0" y1="0" x2="64" y2="64" gradientUnits="userSpaceOnUse">
      <stop stop-color="${from}"/>
      <stop offset="1" stop-color="${to}"/>
    </linearGradient>
  </defs>
  <rect width="64" height="64" rx="14" fill="url(#brandMark)"/>
  <circle cx="32" cy="32" r="11" fill="#fff"/>
  <ellipse cx="32" cy="32" rx="23" ry="8.5" stroke="#fff" stroke-width="3.5" fill="none" transform="rotate(-28 32 32)"/>
</svg>
`;

fs.writeFileSync(OUT, svg, 'utf-8');
console.log(`  Wrote ${path.relative(process.cwd(), OUT)} using ${from} -> ${to}`);

// The theme also ships a few standalone icons with the brand gradient baked
// into their <linearGradient>. Nothing renders them today (our components use
// inline SVG), but retinting them keeps every brand colour in the repo in sync
// with the palette, so they're correct if one is ever used.
const ICON_DIR = path.join(__dirname, '..', 'public', 'assets', 'imgs', 'template', 'icons');
let retinted = 0;
if (fs.existsSync(ICON_DIR)) {
  for (const file of fs.readdirSync(ICON_DIR)) {
    if (!file.endsWith('.svg')) continue;
    const fp = path.join(ICON_DIR, file);
    const src = fs.readFileSync(fp, 'utf-8');
    // Only touch two-stop gradients, which is the brand-gradient shape.
    if ((src.match(/<stop\b/g) || []).length !== 2) continue;
    const next = src
      .replace(/<stop stop-color="#[0-9a-fA-F]{3,8}"\s*\/>/, `<stop stop-color="${from}"/>`)
      .replace(/<stop offset="1" stop-color="#[0-9a-fA-F]{3,8}"\s*\/>/, `<stop offset="1" stop-color="${to}"/>`);
    if (next !== src) {
      fs.writeFileSync(fp, next, 'utf-8');
      retinted++;
    }
  }
}
if (retinted) console.log(`  Retinted ${retinted} brand-gradient icon(s) in assets/imgs/template/icons`);
