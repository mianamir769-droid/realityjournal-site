#!/usr/bin/env node
/**
 * Writes the site's favicons from two sources of truth:
 *   - the $brand-* values in src/styles/elora/utils/_colors.scss (colours)
 *   - SITE_NAME in src/lib/siteConfig.js (the monogram letters)
 *
 * A favicon is a standalone file the browser loads on its own, so it cannot
 * read the site's CSS variables - it is the one place a brand colour has to be
 * written out literally. Generating it from the same source keeps it in sync
 * instead of leaving a stale hex, or another site's initials, behind.
 *
 * Outputs:
 *   public/assets/imgs/template/logo/favicon.svg   linked from _document.js
 *   public/favicon.ico                             browsers request this by
 *                                                  path whether it is linked
 *                                                  or not, so it must not be
 *                                                  left as the Next.js default
 *   public/apple-touch-icon.png                    iOS home screen
 *
 * Run after editing the $brand-* variables or SITE_NAME:
 *     node scripts/generate-favicon.mjs
 */
import fs from 'node:fs';
import path from 'node:path';
import { fileURLToPath } from 'node:url';
import sharp from 'sharp';

const __dirname = path.dirname(fileURLToPath(import.meta.url));
const root = path.join(__dirname, '..');
const COLORS = path.join(root, 'src', 'styles', 'elora', 'utils', '_colors.scss');
const CONFIG = path.join(root, 'src', 'lib', 'siteConfig.js');
const OUT = path.join(root, 'public', 'assets', 'imgs', 'template', 'logo', 'favicon.svg');
const ICO = path.join(root, 'public', 'favicon.ico');
const APPLE = path.join(root, 'public', 'apple-touch-icon.png');

const scss = fs.readFileSync(COLORS, 'utf-8');
function brand(name) {
  const key = '$' + name + ':';
  const at = scss.indexOf(key);
  const m = at === -1 ? null : scss.slice(at, at + 80).match(/#[0-9a-fA-F]{3,8}/);
  if (!m) {
    console.error(`Could not find $${name} in ${path.relative(process.cwd(), COLORS)}`);
    process.exit(1);
  }
  return m[0];
}

// One or two letters, taken from the first words of the site name. Words like
// "the" are skipped so "The Reality Journal" still reads RJ rather than TR.
const SKIP = new Set(['the', 'a', 'an', 'of', 'and']);
function initials() {
  const src = fs.readFileSync(CONFIG, 'utf-8');
  const m = src.match(/export\s+const\s+SITE_NAME\s*=\s*["'`]([^"'`]+)["'`]/);
  if (!m) {
    console.error(`Could not find SITE_NAME in ${path.relative(process.cwd(), CONFIG)}`);
    process.exit(1);
  }
  const words = m[1]
    .split(/[^A-Za-z0-9]+/)
    .filter(Boolean)
    .filter((w, i, arr) => arr.length === 1 || !SKIP.has(w.toLowerCase()));
  if (!words.length) return '?';
  // A single-word name gets one letter rather than two from the same word,
  // which reads as a typo at 16px.
  return words.slice(0, 2).map((w) => w[0].toUpperCase()).join('');
}

const from = brand('brand-1');
const to = brand('brand-2');
const mark = initials();

// Two letters need to be narrower than one to fit the same optical box. A
// heavy sans is deliberate: at the 16px the browser tab actually uses, a
// serif's thin strokes disappear and the mark turns to mush.
const fontSize = mark.length > 1 ? 27 : 36;

const svg = `<!-- Generated by scripts/generate-favicon.mjs from the $brand-* values in
     src/styles/elora/utils/_colors.scss and SITE_NAME in src/lib/siteConfig.js.
     Do not edit by hand. -->
<svg width="64" height="64" viewBox="0 0 64 64" xmlns="http://www.w3.org/2000/svg">
  <defs>
    <linearGradient id="brandMark" x1="0" y1="0" x2="64" y2="64" gradientUnits="userSpaceOnUse">
      <stop stop-color="${from}"/>
      <stop offset="1" stop-color="${to}"/>
    </linearGradient>
  </defs>
  <rect width="64" height="64" rx="14" fill="url(#brandMark)"/>
  <text x="32" y="32" fill="#fff" text-anchor="middle" dominant-baseline="central"
        font-family="'Arial Black', 'Helvetica Neue', Arial, sans-serif"
        font-weight="900" font-size="${fontSize}">${mark}</text>
</svg>
`;

fs.writeFileSync(OUT, svg, 'utf-8');
console.log(`  Wrote ${path.relative(process.cwd(), OUT)} - "${mark}" on ${from} -> ${to}`);

// ICO is a container: a 6-byte header, one 16-byte directory entry per image,
// then the image data. Every size here is stored as a PNG, which ICO has
// allowed since Vista and every browser we care about reads.
async function writeIco(sizes) {
  const pngs = [];
  for (const size of sizes) {
    pngs.push(await sharp(Buffer.from(svg)).resize(size, size).png().toBuffer());
  }
  const header = Buffer.alloc(6);
  header.writeUInt16LE(0, 0);            // reserved
  header.writeUInt16LE(1, 2);            // type 1 = icon
  header.writeUInt16LE(sizes.length, 4);
  const dir = Buffer.alloc(16 * sizes.length);
  let offset = header.length + dir.length;
  sizes.forEach((size, i) => {
    const at = i * 16;
    dir.writeUInt8(size >= 256 ? 0 : size, at);      // 0 means 256
    dir.writeUInt8(size >= 256 ? 0 : size, at + 1);
    dir.writeUInt8(0, at + 2);                       // palette colours
    dir.writeUInt8(0, at + 3);                       // reserved
    dir.writeUInt16LE(1, at + 4);                    // colour planes
    dir.writeUInt16LE(32, at + 6);                   // bits per pixel
    dir.writeUInt32LE(pngs[i].length, at + 8);
    dir.writeUInt32LE(offset, at + 12);
    offset += pngs[i].length;
  });
  fs.writeFileSync(ICO, Buffer.concat([header, dir, ...pngs]));
}

await writeIco([16, 32, 48]);
console.log(`  Wrote ${path.relative(process.cwd(), ICO)} (16, 32, 48)`);

await sharp(Buffer.from(svg)).resize(180, 180).png().toFile(APPLE);
console.log(`  Wrote ${path.relative(process.cwd(), APPLE)} (180)`);

// The theme also ships a few standalone icons with the brand gradient baked
// into their <linearGradient>. Nothing renders them today (our components use
// inline SVG), but retinting them keeps every brand colour in the repo in sync
// with the palette, so they're correct if one is ever used.
const ICON_DIR = path.join(root, 'public', 'assets', 'imgs', 'template', 'icons');
let retinted = 0;
if (fs.existsSync(ICON_DIR)) {
  for (const file of fs.readdirSync(ICON_DIR)) {
    if (!file.endsWith('.svg')) continue;
    const fp = path.join(ICON_DIR, file);
    const src = fs.readFileSync(fp, 'utf-8');
    // Only touch two-stop gradients, which is the brand-gradient shape.
    if ((src.match(/<stop\b/g) || []).length !== 2) continue;
    const next = src
      .replace(/<stop stop-color="#[0-9a-fA-F]{3,8}"\s*\/>/, `<stop stop-color="${from}"/>`)
      .replace(/<stop offset="1" stop-color="#[0-9a-fA-F]{3,8}"\s*\/>/, `<stop offset="1" stop-color="${to}"/>`);
    if (next !== src) {
      fs.writeFileSync(fp, next, 'utf-8');
      retinted++;
    }
  }
}
if (retinted) console.log(`  Retinted ${retinted} brand-gradient icon(s) in assets/imgs/template/icons`);
